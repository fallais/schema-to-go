import { generateSync } from 'json-schema-faker';
import { JsonToGo } from './json-to-go';

export interface SchemaToGoOptions {
  inline: boolean;
  omitempty: boolean;
}

export interface SchemaToGoResult {
  go: string;
  error?: string;
}

const DEFAULT_TYPE_NAME = 'AutoGenerated';

// Fixed seed and forced optionals so the same schema always yields the same Go code
const FAKER_OPTIONS = {
  seed: 1,
  alwaysFakeOptionals: true,
  optionalsProbability: 1,
  fillProperties: false,
  useExamplesValue: true,
  minItems: 1,
};

export function schemaToGo(input: string, options: SchemaToGoOptions): SchemaToGoResult {
  if (!input.trim()) {
    return { go: '' };
  }

  let schema: unknown;
  try {
    schema = JSON.parse(input);
  } catch (err) {
    return { go: '', error: `Invalid JSON: ${(err as Error).message}` };
  }
  if (typeof schema !== 'object' || schema === null || Array.isArray(schema)) {
    return { go: '', error: 'A JSON Schema must be an object' };
  }

  let sample: unknown;
  try {
    sample = generateSync(schema as Record<string, unknown>, FAKER_OPTIONS);
  } catch (err) {
    return { go: '', error: `Invalid JSON Schema: ${(err as Error).message}` };
  }

  const title = (schema as { title?: unknown }).title;
  const typeName = typeof title === 'string' && title.trim() ? title : DEFAULT_TYPE_NAME;

  return new JsonToGo().jsonToGo(
    JSON.stringify(sample),
    typeName,
    !options.inline,
    false,
    options.omitempty,
  );
}
