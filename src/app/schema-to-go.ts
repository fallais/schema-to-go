import { format, NAMING_FAILED, singular, uniqueName } from './naming';

export interface SchemaToGoOptions {
  inline: boolean;
  omitempty: boolean;
  pointers: boolean;
}

export interface SchemaToGoResult {
  go: string;
  error?: string;
}

const DEFAULT_TYPE_NAME = 'AutoGenerated';

export function schemaToGo(input: string, options: SchemaToGoOptions): SchemaToGoResult {
  if (!input.trim()) {
    return { go: '' };
  }

  let schema: unknown;
  try {
    schema = JSON.parse(input);
  } catch (err) {
    return { go: '', error: `Invalid JSON: ${(err as Error).message}` };
  }
  if (!isObject(schema)) {
    return { go: '', error: 'A JSON Schema must be an object' };
  }

  try {
    return { go: new Generator(schema, options).run() };
  } catch (err) {
    return { go: '', error: `Invalid JSON Schema: ${(err as Error).message}` };
  }
}

type Schema = Record<string, any>;

type GoType =
  | { kind: 'basic'; name: string; note?: string }
  | { kind: 'struct'; fields: Field[] }
  | { kind: 'slice'; elem: GoType }
  | { kind: 'map'; elem: GoType }
  | { kind: 'pointer'; elem: GoType };

interface Field {
  name: string;
  type: GoType;
  jsonName?: string;
  omitempty?: boolean;
  doc?: string;
  embedded?: boolean;
}

type Decl =
  | { kind: 'struct'; name: string; doc?: string; fields: Field[] }
  | { kind: 'enum'; name: string; doc?: string; base: string; values: (string | number)[] }
  | { kind: 'alias'; name: string; doc?: string; type: GoType };

interface Ctx {
  hint: string;
  parent: string;
}

const ANY: GoType = { kind: 'basic', name: 'any' };

const INTEGER_FORMATS = new Set(['int8', 'int16', 'int32', 'int64', 'uint', 'uint8', 'uint16', 'uint32', 'uint64']);

const SHAPE_KEYWORDS = [
  'type', 'properties', 'items', 'prefixItems', 'enum', 'const', 'allOf', 'oneOf', 'anyOf',
  'additionalProperties', 'patternProperties', '$ref',
];

class Generator {
  // Declarations in output order; null marks a slot that was reserved then dropped or is still in progress
  private readonly decls: (Decl | null)[] = [];
  private readonly declIndex = new Map<string, number>();
  // Keyed by target schema so different $ref spellings of the same schema share one type
  private readonly refs = new Map<Schema, GoType>();
  private readonly inlining = new Set<Schema>();
  private readonly ids = new Map<string, Schema>();
  private readonly defNames = new Map<Schema, string>();
  private readonly checking = new Set<Schema>();
  private readonly rootName: string;

  constructor(
    private readonly root: Schema,
    private readonly opts: SchemaToGoOptions,
  ) {
    this.rootName = titleName(root) ?? DEFAULT_TYPE_NAME;
    this.indexIds(root);
    for (const [, defs] of this.definitions()) {
      for (const [key, def] of Object.entries(defs)) {
        if (isObject(def)) this.defNames.set(def, format(key));
      }
    }
  }

  run(): string {
    if (typeof this.root['$ref'] === 'string') {
      this.ref(this.root['$ref'], { hint: this.rootName, parent: '' });
    } else if (SHAPE_KEYWORDS.some(k => k in this.root)) {
      this.declareNamed(this.root, this.rootName);
    }
    this.declareDefinitions();

    return this.decls
      .filter((d): d is Decl => d !== null)
      .map(d => this.renderDecl(d))
      .join('\n\n');
  }

  // Emits every $defs / definitions entry, including those never referenced
  private declareDefinitions(): void {
    for (const [, defs] of this.definitions()) {
      for (const [key, def] of Object.entries(defs)) {
        if (isObject(def) && !this.refs.has(def)) this.declareNamed(def, format(key));
      }
    }
  }

  private definitions(): [string, Schema][] {
    return ['$defs', 'definitions']
      .filter(container => isObject(this.root[container]))
      .map(container => [container, this.root[container]]);
  }

  private declareNamed(schema: Schema, baseName: string): GoType {
    const slot = this.decls.push(null) - 1;
    const name = uniqueName(baseName, new Set(this.declIndex.keys()));
    this.declIndex.set(name, slot);
    const named: GoType = { kind: 'basic', name };
    this.refs.set(schema, named);

    const doc = description(schema);
    const values = enumValues(schema);
    if (this.isStruct(schema)) {
      this.decls[slot] = { kind: 'struct', name, doc, fields: this.fields(schema, name) };
    } else if (values) {
      this.decls[slot] = { kind: 'enum', name, doc, ...values };
    } else {
      const type = this.typeOf(schema, { hint: name, parent: name });
      this.decls[slot] = { kind: 'alias', name, doc, type: type.kind === 'pointer' ? type.elem : type };
    }
    return named;
  }

  // Declares an anonymous struct or enum, reusing an identical declaration with the same name
  private declareAnonymous(build: () => Decl, candidates: string[]): GoType {
    const slot = this.decls.push(null) - 1;
    const decl = build();
    const signature = this.signature(decl);

    for (const name of candidates) {
      const index = this.declIndex.get(name);
      if (index === undefined) {
        return this.place(decl, name, slot);
      }
      const existing = this.decls[index];
      if (existing && this.signature(existing) === signature) {
        return { kind: 'basic', name };
      }
    }
    return this.place(decl, uniqueName(candidates[0], new Set(this.declIndex.keys())), slot);
  }

  private place(decl: Decl, name: string, slot: number): GoType {
    decl.name = name;
    this.decls[slot] = decl;
    this.declIndex.set(name, slot);
    return { kind: 'basic', name };
  }

  private signature(decl: Decl): string {
    if (decl.kind === 'struct') return this.renderType({ kind: 'struct', fields: decl.fields }, 0);
    if (decl.kind === 'enum') return JSON.stringify([decl.base, decl.values]);
    return this.renderType(decl.type, 0);
  }

  private typeOf(schema: unknown, ctx: Ctx): GoType {
    if (!isObject(schema)) return ANY;
    if (typeof schema['$ref'] === 'string') return this.ref(schema['$ref'], ctx);

    const type = this.nonNullType(schema, ctx);
    return isNullable(schema) ? pointer(type) : type;
  }

  private nonNullType(schema: Schema, ctx: Ctx): GoType {
    const values = enumValues(schema);
    if (values) {
      return this.declareAnonymous(
        () => ({ kind: 'enum', name: '', doc: description(schema), ...values }),
        [ctx.hint, ctx.parent + ctx.hint],
      );
    }
    if (Array.isArray(schema['enum'])) return inferType(schema['enum'].filter(v => v !== null));
    if ('const' in schema) return inferType([schema['const']]);
    if (this.isStruct(schema)) return this.structType(schema, ctx);
    if (Array.isArray(schema['oneOf'])) return this.unionType(schema['oneOf'], 'oneOf', ctx);
    if (Array.isArray(schema['anyOf'])) return this.unionType(schema['anyOf'], 'anyOf', ctx);

    const types = nonNullTypes(schema);
    if (types.length > 1) {
      if (types.every(t => t === 'integer' || t === 'number')) return basic('float64');
      return { kind: 'basic', name: 'any', note: `type: ${types.join(' | ')}` };
    }

    switch (types[0]) {
      case 'string':
        if (schema['format'] === 'date-time') return basic('time.Time');
        if (schema['format'] === 'byte' || schema['contentEncoding'] === 'base64') return { kind: 'slice', elem: basic('byte') };
        return basic('string');
      case 'integer':
        return basic(INTEGER_FORMATS.has(schema['format']) ? schema['format'] : 'int');
      case 'number':
        return basic(schema['format'] === 'float' ? 'float32' : 'float64');
      case 'boolean':
        return basic('bool');
      case 'array':
        return this.arrayType(schema, ctx);
      case 'object':
        return this.mapType(schema, ctx);
      default:
        return ANY;
    }
  }

  private structType(schema: Schema, ctx: Ctx): GoType {
    const name = titleName(schema) ?? ctx.hint;
    if (this.opts.inline) {
      return { kind: 'struct', fields: this.fields(schema, name) };
    }
    return this.declareAnonymous(
      () => ({ kind: 'struct', name: '', doc: description(schema), fields: this.fields(schema, name) }),
      [name, ctx.parent + name],
    );
  }

  private arrayType(schema: Schema, ctx: Ctx): GoType {
    const itemCtx = { hint: singular(ctx.hint), parent: ctx.parent };
    const tuple = Array.isArray(schema['prefixItems']) ? schema['prefixItems'] : Array.isArray(schema['items']) ? schema['items'] : null;
    if (tuple) {
      const types = tuple.map(item => this.typeOf(item, itemCtx));
      const rendered = new Set(types.map(t => this.renderType(t, 0)));
      return { kind: 'slice', elem: rendered.size === 1 ? types[0] : ANY };
    }
    return { kind: 'slice', elem: 'items' in schema ? this.typeOf(schema['items'], itemCtx) : ANY };
  }

  private mapType(schema: Schema, ctx: Ctx): GoType {
    const valueCtx = { hint: singular(ctx.hint), parent: ctx.parent };
    if (isObject(schema['additionalProperties'])) {
      return { kind: 'map', elem: this.typeOf(schema['additionalProperties'], valueCtx) };
    }
    const patterns = isObject(schema['patternProperties']) ? Object.values(schema['patternProperties']) : [];
    if (patterns.length === 1) {
      return { kind: 'map', elem: this.typeOf(patterns[0], valueCtx) };
    }
    return { kind: 'map', elem: ANY };
  }

  private unionType(variants: unknown[], keyword: string, ctx: Ctx): GoType {
    const nonNull = variants.filter(v => !isNullSchema(v));
    const nullable = nonNull.length < variants.length;
    if (nonNull.length === 0) return ANY;

    let type: GoType;
    if (nonNull.length === 1) {
      type = this.typeOf(nonNull[0], ctx);
    } else {
      // Only named variants are declared, anonymous objects would get meaningless names
      const labels = nonNull.map(v => this.variantLabel(v, ctx));
      const unique = new Set(labels);
      if (unique.size === 1 && labels[0] !== 'object') {
        type = this.typeOf(nonNull[0], ctx);
      } else if (labels.every(l => /^(u?int|float)/.test(l))) {
        type = basic('float64');
      } else {
        type = { kind: 'basic', name: 'any', note: `${keyword}: ${[...unique].join(' | ')}` };
      }
    }
    return nullable ? pointer(type) : type;
  }

  private variantLabel(variant: unknown, ctx: Ctx): string {
    if (!isObject(variant)) return 'any';
    if (typeof variant['$ref'] === 'string') return label(this.ref(variant['$ref'], ctx));
    if (this.isStruct(variant) || nonNullTypes(variant)[0] === 'object') return 'object';
    if (Array.isArray(variant['enum'])) return 'enum';
    return label(this.typeOf(variant, ctx));
  }

  private ref(ref: string, ctx: Ctx): GoType {
    const target = this.resolve(ref);
    if (!target) return { kind: 'basic', name: 'any', note: `unresolved $ref: ${ref}` };

    const nullable = isNullable(target);
    const name = this.defNames.get(target) ?? refName(ref, this.rootName);
    let type = this.refs.get(target);
    if (!type) {
      if (this.isStruct(target) || enumValues(target)) {
        type = this.declareNamed(target, name);
      } else if (this.inlining.has(target)) {
        return ANY;
      } else {
        this.inlining.add(target);
        type = this.typeOf(target, { hint: name, parent: ctx.parent });
        this.inlining.delete(target);
        this.refs.set(target, type);
        return type;
      }
    }
    return nullable ? pointer(type) : type;
  }

  private resolve(ref: string): Schema | undefined {
    if (ref === '#') return this.root;
    if (ref.startsWith('#/')) {
      let node: any = this.root;
      for (const raw of ref.slice(2).split('/')) {
        const key = decodeURIComponent(raw).replace(/~1/g, '/').replace(/~0/g, '~');
        node = isObject(node) || Array.isArray(node) ? (node as any)[key] : undefined;
      }
      if (!isObject(node)) throw new Error(`Unresolved $ref: ${ref}`);
      return node;
    }
    const byId = this.ids.get(ref);
    if (byId) return byId;
    if (ref.startsWith('#')) throw new Error(`Unresolved $ref: ${ref}`);
    return undefined;
  }

  private indexIds(node: unknown): void {
    if (Array.isArray(node)) {
      node.forEach(n => this.indexIds(n));
    } else if (isObject(node)) {
      if (typeof node['$anchor'] === 'string') this.ids.set('#' + node['$anchor'], node);
      for (const key of ['$id', 'id']) {
        if (typeof node[key] === 'string' && node !== this.root) this.ids.set(node[key], node);
      }
      for (const [key, value] of Object.entries(node)) {
        if (!['enum', 'const', 'default', 'examples', 'example'].includes(key)) this.indexIds(value);
      }
    }
  }

  private isStruct(schema: Schema): boolean {
    const types = nonNullTypes(schema);
    if (types.length > 0 && !(types.length === 1 && types[0] === 'object')) return false;
    if (isObject(schema['properties'])) return true;
    if (!Array.isArray(schema['allOf']) || this.checking.has(schema)) return false;
    this.checking.add(schema);
    const result = this.allOfParts(schema).some(part => this.isStructPart(part));
    this.checking.delete(schema);
    return result;
  }

  // allOf parts, with anyOf / oneOf of structs expanded since any of their fields may be present
  private allOfParts(schema: Schema): unknown[] {
    const parts: unknown[] = [];
    for (const part of Array.isArray(schema['allOf']) ? schema['allOf'] : []) {
      const variants = isObject(part) ? (part['anyOf'] ?? part['oneOf']) : undefined;
      if (isObject(part) && !part['$ref'] && !isObject(part['properties']) && Array.isArray(variants)) {
        const nonNull = variants.filter(v => !isNullSchema(v));
        if (nonNull.length > 0 && nonNull.every(v => this.isStructPart(v))) {
          parts.push(...nonNull);
          continue;
        }
      }
      parts.push(part);
    }
    return parts;
  }

  private isStructPart(part: unknown): boolean {
    if (!isObject(part)) return false;
    if (typeof part['$ref'] === 'string') {
      const target = this.resolve(part['$ref']);
      return !!target && this.isStruct(target);
    }
    return this.isStruct(part);
  }

  private fields(schema: Schema, parent: string, used = new Set<string>()): Field[] {
    const fields: Field[] = [];
    const jsonNames = new Set<string>();
    const addField = (field: Field) => {
      if (field.jsonName === undefined || jsonNames.has(field.jsonName)) return;
      jsonNames.add(field.jsonName);
      fields.push(field);
    };

    const parts = this.allOfParts(schema);
    const required = new Set<string>(Array.isArray(schema['required']) ? schema['required'] : []);
    // Only direct allOf parts make fields required, anyOf / oneOf variants stay optional
    for (const part of Array.isArray(schema['allOf']) ? schema['allOf'] : []) {
      if (isObject(part) && Array.isArray(part['required']) && !part['$ref']) {
        part['required'].forEach((r: string) => required.add(r));
      }
    }

    // allOf with a $ref becomes an embedded struct, inline parts are merged
    for (const part of parts) {
      if (!this.isStructPart(part)) continue;
      const p = part as Schema;
      if (typeof p['$ref'] !== 'string') {
        this.fields({ ...p, required: [...required] }, parent, used).forEach(addField);
        continue;
      }

      const type = this.ref(p['$ref'], { hint: parent, parent });
      const named = type.kind === 'pointer' ? type.elem : type;
      const embedded = this.structFields(named);
      if (embedded) {
        const flattened = this.flatten(embedded);
        // encoding/json ignores fields that conflict at the same depth, so merge them instead
        if (flattened.some(f => jsonNames.has(f.jsonName!))) {
          flattened.forEach(f => {
            if (jsonNames.has(f.jsonName!)) return;
            const name = uniqueName(f.name, used);
            used.add(name);
            addField({ ...f, name });
          });
          continue;
        }
        flattened.forEach(f => jsonNames.add(f.jsonName!));
      }
      if (named.kind === 'basic') used.add(named.name);
      fields.push({ name: '', type: this.isInProgress(named) ? pointer(named) : named, embedded: true });
    }

    const properties = isObject(schema['properties']) ? schema['properties'] : {};
    for (const [key, prop] of Object.entries(properties)) {
      if (jsonNames.has(key)) continue;
      const name = uniqueName(format(key), used);
      used.add(name);

      let type = this.typeOf(prop, { hint: name, parent });
      const optional = !required.has(key);
      // A struct cannot contain itself by value
      if ((optional && this.opts.pointers && canPoint(type)) || this.isInProgress(type)) type = pointer(type);

      addField({
        name,
        type,
        jsonName: key,
        omitempty: this.opts.omitempty || optional,
        doc: description(prop),
      });
    }
    return fields;
  }

  private structFields(type: GoType): Field[] | undefined {
    if (type.kind !== 'basic') return undefined;
    const index = this.declIndex.get(type.name);
    const decl = index === undefined ? null : this.decls[index];
    return decl?.kind === 'struct' ? decl.fields : undefined;
  }

  // Fields of a struct with its embedded structs expanded
  private flatten(fields: Field[]): Field[] {
    return fields.flatMap(f => {
      if (!f.embedded) return [f];
      const inner = this.structFields(f.type.kind === 'pointer' ? f.type.elem : f.type);
      return inner ? this.flatten(inner) : [];
    });
  }

  private isInProgress(type: GoType): boolean {
    if (type.kind !== 'basic') return false;
    const index = this.declIndex.get(type.name);
    return index !== undefined && this.decls[index] === null;
  }

  private renderDecl(decl: Decl): string {
    const doc = comment(decl.doc, '');
    switch (decl.kind) {
      case 'struct':
        return `${doc}type ${decl.name} ${this.renderType({ kind: 'struct', fields: decl.fields }, 0)}`;
      case 'alias':
        return `${doc}type ${decl.name} ${this.renderType(decl.type, 0)}`;
      case 'enum': {
        const used = new Set<string>();
        const consts = decl.values.map((value, i) => {
          const suffix = typeof value === 'number' ? String(value).replace('-', 'Minus').replace('.', '_') : format(value);
          const name = uniqueName(decl.name + (suffix === NAMING_FAILED ? `Value${i + 1}` : suffix), used);
          used.add(name);
          return `\t${name} ${decl.name} = ${JSON.stringify(value)}\n`;
        });
        return `${doc}type ${decl.name} ${decl.base}\n\nconst (\n${consts.join('')})`;
      }
    }
  }

  private renderType(type: GoType, depth: number): string {
    switch (type.kind) {
      case 'basic':
        return type.name;
      case 'pointer':
        return '*' + this.renderType(type.elem, depth);
      case 'slice':
        return '[]' + this.renderType(type.elem, depth);
      case 'map':
        return 'map[string]' + this.renderType(type.elem, depth);
      case 'struct': {
        const indent = '\t'.repeat(depth + 1);
        const body = type.fields.map(f => {
          const doc = comment(f.doc, indent);
          if (f.embedded) return `${doc}${indent}${this.renderType(f.type, depth + 1)}\n`;
          const tag = `\`json:"${f.jsonName}${f.omitempty ? ',omitempty' : ''}"\``;
          const note = noteOf(f.type);
          return `${doc}${indent}${f.name} ${this.renderType(f.type, depth + 1)} ${tag}${note ? ' // ' + note : ''}\n`;
        });
        return `struct {\n${body.join('')}${'\t'.repeat(depth)}}`;
      }
    }
  }
}

function isObject(value: unknown): value is Schema {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function basic(name: string): GoType {
  return { kind: 'basic', name };
}

function pointer(type: GoType): GoType {
  if (type.kind === 'pointer' || (type.kind === 'basic' && type.name === 'any')) return type;
  return { kind: 'pointer', elem: type };
}

// Slices, maps and any are already nil-able
function canPoint(type: GoType): boolean {
  return type.kind === 'struct' || (type.kind === 'basic' && type.name !== 'any');
}

// One-line description of a type, inline structs are shown as "object"
function label(type: GoType): string {
  switch (type.kind) {
    case 'basic':
      return type.name;
    case 'pointer':
      return '*' + label(type.elem);
    case 'slice':
      return '[]' + label(type.elem);
    case 'map':
      return 'map[string]' + label(type.elem);
    case 'struct':
      return 'object';
  }
}

function noteOf(type: GoType): string | undefined {
  if (type.kind === 'basic') return type.note;
  if (type.kind === 'pointer') return noteOf(type.elem);
  return undefined;
}

function comment(text: string | undefined, indent: string): string {
  if (!text) return '';
  return text
    .trim()
    .split('\n')
    .map(line => `${indent}// ${line.trimEnd()}`.trimEnd() + '\n')
    .join('');
}

function description(schema: unknown): string | undefined {
  return isObject(schema) && typeof schema['description'] === 'string' ? schema['description'] : undefined;
}

function titleName(schema: Schema): string | undefined {
  if (typeof schema['title'] !== 'string') return undefined;
  const name = format(schema['title']);
  return name === NAMING_FAILED ? undefined : name;
}

function refName(ref: string, rootName: string): string {
  const last = ref.split(/[/#]/).filter(Boolean).pop();
  if (!last) return rootName;
  const name = format(decodeURIComponent(last).replace(/~1/g, '/').replace(/~0/g, '~').replace(/\.json$/, ''));
  return name === NAMING_FAILED ? rootName : name;
}

function nonNullTypes(schema: Schema): string[] {
  const type = schema['type'];
  const types: string[] = Array.isArray(type) ? type : typeof type === 'string' ? [type] : [];
  const nonNull = types.filter(t => t !== 'null');
  if (nonNull.length > 0 || types.length > 0) return nonNull;
  if ('properties' in schema || 'additionalProperties' in schema || 'patternProperties' in schema) return ['object'];
  if ('items' in schema || 'prefixItems' in schema) return ['array'];
  return [];
}

function isNullable(schema: Schema): boolean {
  const type = schema['type'];
  return (
    schema['nullable'] === true ||
    (Array.isArray(type) && type.includes('null')) ||
    (Array.isArray(schema['enum']) && schema['enum'].includes(null))
  );
}

function isNullSchema(schema: unknown): boolean {
  if (!isObject(schema)) return false;
  return schema['type'] === 'null' || (Array.isArray(schema['enum']) && schema['enum'].length === 1 && schema['enum'][0] === null);
}

// Returns the Go base type and values when the enum can become a named type with constants
function enumValues(schema: Schema): { base: string; values: (string | number)[] } | undefined {
  if (!Array.isArray(schema['enum'])) return undefined;
  const values = schema['enum'].filter(v => v !== null);
  if (values.length < 2) return undefined;
  if (values.every(v => typeof v === 'string')) return { base: 'string', values };
  if (values.every(v => Number.isInteger(v))) return { base: 'int', values };
  if (values.every(v => typeof v === 'number')) return { base: 'float64', values };
  return undefined;
}

function inferType(values: unknown[]): GoType {
  const types = new Set(
    values.map(v => {
      if (typeof v === 'string') return 'string';
      if (typeof v === 'boolean') return 'bool';
      if (typeof v === 'number') return Number.isInteger(v) ? 'int' : 'float64';
      return 'any';
    }),
  );
  if (types.size === 1) return basic([...types][0]);
  if ([...types].every(t => t === 'int' || t === 'float64')) return basic('float64');
  return ANY;
}
