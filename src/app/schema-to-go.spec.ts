import { schemaToGo, SchemaToGoOptions } from './schema-to-go';

const flat: SchemaToGoOptions = { inline: false, omitempty: false, pointers: false };
const inline: SchemaToGoOptions = { ...flat, inline: true };

function go(schema: object, options = flat): string {
  const { go, error } = schemaToGo(JSON.stringify(schema), options);
  expect(error).toBeUndefined();
  return go;
}

const lines = (...l: string[]) => l.join('\n');

describe('schemaToGo input handling', () => {
  it('returns nothing for empty input', () => {
    expect(schemaToGo('  ', flat)).toEqual({ go: '' });
  });

  it('reports invalid JSON', () => {
    expect(schemaToGo('{', flat).error).toMatch(/^Invalid JSON/);
  });

  it('rejects non-object schemas', () => {
    expect(schemaToGo('[]', flat).error).toBe('A JSON Schema must be an object');
  });

  it('reports unresolved local references', () => {
    const schema = { type: 'object', properties: { x: { $ref: '#/$defs/Missing' } } };
    expect(schemaToGo(JSON.stringify(schema), flat).error).toBe('Invalid JSON Schema: Unresolved $ref: #/$defs/Missing');
  });
});

describe('schemaToGo types', () => {
  it('maps primitives, formats and required fields', () => {
    expect(
      go({
        title: 'User',
        type: 'object',
        required: ['id'],
        properties: {
          id: { type: 'integer', format: 'int64', description: 'Unique identifier' },
          name: { type: 'string' },
          price: { type: 'number' },
          ratio: { type: 'number', format: 'float' },
          active: { type: 'boolean' },
          at: { type: 'string', format: 'date-time' },
          raw: { type: 'string', format: 'byte' },
          tags: { type: 'array', items: { type: 'string' } },
        },
      }),
    ).toBe(
      lines(
        'type User struct {',
        '\t// Unique identifier',
        '\tID int64 `json:"id"`',
        '\tName string `json:"name,omitempty"`',
        '\tPrice float64 `json:"price,omitempty"`',
        '\tRatio float32 `json:"ratio,omitempty"`',
        '\tActive bool `json:"active,omitempty"`',
        '\tAt time.Time `json:"at,omitempty"`',
        '\tRaw []byte `json:"raw,omitempty"`',
        '\tTags []string `json:"tags,omitempty"`',
        '}',
      ),
    );
  });

  it('reuses $ref definitions', () => {
    expect(
      go({
        type: 'object',
        required: ['home', 'work'],
        properties: { home: { $ref: '#/$defs/Address' }, work: { $ref: '#/$defs/Address' } },
        $defs: { Address: { type: 'object', description: 'A postal address', required: ['city'], properties: { city: { type: 'string' } } } },
      }),
    ).toBe(
      lines(
        'type AutoGenerated struct {',
        '\tHome Address `json:"home"`',
        '\tWork Address `json:"work"`',
        '}',
        '',
        '// A postal address',
        'type Address struct {',
        '\tCity string `json:"city"`',
        '}',
      ),
    );
  });

  it('maps additionalProperties to maps', () => {
    expect(
      go({
        type: 'object',
        required: ['labels', 'extra', 'byPattern'],
        properties: {
          labels: { type: 'object', additionalProperties: { type: 'string' } },
          extra: { type: 'object' },
          byPattern: { type: 'object', patternProperties: { '^x-': { type: 'integer' } } },
        },
      }),
    ).toBe(
      lines(
        'type AutoGenerated struct {',
        '\tLabels map[string]string `json:"labels"`',
        '\tExtra map[string]any `json:"extra"`',
        '\tByPattern map[string]int `json:"byPattern"`',
        '}',
      ),
    );
  });

  it('turns nullable types into pointers', () => {
    const out = go({
      type: 'object',
      required: ['a', 'b', 'c'],
      properties: {
        a: { type: ['string', 'null'] },
        b: { anyOf: [{ $ref: '#/$defs/Item' }, { type: 'null' }] },
        c: { type: 'integer', nullable: true },
      },
      $defs: { Item: { type: 'object', properties: { x: { type: 'boolean' } } } },
    });
    expect(out).toContain('\tA *string `json:"a"`');
    expect(out).toContain('\tB *Item `json:"b"`');
    expect(out).toContain('\tC *int `json:"c"`');
  });

  it('declares enums with constants', () => {
    expect(
      go({
        type: 'object',
        required: ['color', 'level'],
        properties: { color: { enum: ['red', 'dark-blue'] }, level: { type: 'integer', enum: [1, 2] } },
      }),
    ).toBe(
      lines(
        'type AutoGenerated struct {',
        '\tColor Color `json:"color"`',
        '\tLevel Level `json:"level"`',
        '}',
        '',
        'type Color string',
        '',
        'const (',
        '\tColorRed Color = "red"',
        '\tColorDarkBlue Color = "dark-blue"',
        ')',
        '',
        'type Level int',
        '',
        'const (',
        '\tLevel1 Level = 1',
        '\tLevel2 Level = 2',
        ')',
      ),
    );
  });

  it('handles recursive schemas', () => {
    expect(
      go({
        $ref: '#/$defs/Node',
        $defs: { Node: { type: 'object', required: ['children'], properties: { children: { type: 'array', items: { $ref: '#/$defs/Node' } } } } },
      }),
    ).toBe(lines('type Node struct {', '\tChildren []Node `json:"children"`', '}'));
  });

  it('handles references to the root schema', () => {
    expect(go({ title: 'Tree', type: 'object', properties: { parent: { $ref: '#' } } })).toContain('Parent *Tree `json:"parent,omitempty"`');
  });

  it('falls back to any for unions, with a note', () => {
    const out = go({
      type: 'object',
      required: ['v', 'w', 'n'],
      properties: {
        v: { oneOf: [{ type: 'string' }, { $ref: '#/$defs/Item' }] },
        w: { type: ['string', 'integer'] },
        n: { anyOf: [{ type: 'integer' }, { type: 'number' }] },
      },
      $defs: { Item: { type: 'object', properties: { x: { type: 'boolean' } } } },
    });
    expect(out).toContain('\tV any `json:"v"` // oneOf: string | Item');
    expect(out).toContain('\tW any `json:"w"` // type: string | integer');
    expect(out).toContain('\tN float64 `json:"n"`');
    expect(out).toContain('type Item struct');
  });

  it('embeds allOf references and merges inline parts', () => {
    expect(
      go({
        title: 'Dog',
        allOf: [{ $ref: '#/$defs/Pet' }, { type: 'object', required: ['bark'], properties: { bark: { type: 'boolean' } } }],
        $defs: { Pet: { type: 'object', required: ['name'], properties: { name: { type: 'string' } } } },
      }),
    ).toBe(
      lines(
        'type Dog struct {',
        '\tPet',
        '\tBark bool `json:"bark"`',
        '}',
        '',
        'type Pet struct {',
        '\tName string `json:"name"`',
        '}',
      ),
    );
  });

  it('uses pointers for structs that contain themselves', () => {
    expect(go({ title: 'Person', type: 'object', required: ['partner'], properties: { partner: { $ref: '#' } } })).toBe(
      lines('type Person struct {', '\tPartner *Person `json:"partner"`', '}'),
    );
  });

  it('merges allOf references whose fields would conflict once embedded', () => {
    const out = go({
      title: 'Rules',
      allOf: [{ $ref: '#/$defs/A' }, { $ref: '#/$defs/B' }],
      $defs: {
        A: { type: 'object', properties: { x: { type: 'string' }, a: { type: 'string' } } },
        B: { type: 'object', properties: { x: { type: 'string' }, b: { type: 'string' } } },
      },
    });
    expect(out).toContain(lines('type Rules struct {', '\tA', '\tB string `json:"b,omitempty"`', '}'));
  });

  it('expands anyOf of structs inside allOf as optional fields', () => {
    const out = go({
      title: 'Config',
      allOf: [
        { type: 'object', required: ['name'], properties: { name: { type: 'string' } } },
        { anyOf: [{ $ref: '#/$defs/Files' }, { type: 'object', required: ['include'], properties: { include: { type: 'string' } } }] },
      ],
      $defs: { Files: { type: 'object', properties: { files: { type: 'array', items: { type: 'string' } } } } },
    });
    expect(out).toContain(
      lines('type Config struct {', '\tName string `json:"name"`', '\tFiles', '\tInclude string `json:"include,omitempty"`', '}'),
    );
  });

  it('keeps union notes on one line', () => {
    const out = go(
      { type: 'object', properties: { v: { oneOf: [{ type: 'string' }, { type: 'array', items: { type: 'object', properties: { a: { type: 'string' } } } }] } } },
      inline,
    );
    expect(out).toContain('V any `json:"v,omitempty"` // oneOf: string | []object\n');
  });

  it('names slice element types in singular', () => {
    const out = go({
      type: 'object',
      properties: {
        addresses: { type: 'array', items: { type: 'object', properties: { city: { type: 'string' } } } },
        data: { type: 'array', items: { type: 'object', properties: { a: { type: 'string' } } } },
      },
    });
    expect(out).toContain('Addresses []Address `json:"addresses,omitempty"`');
    expect(out).toContain('Data []DataItem `json:"data,omitempty"`');
    expect(out).toContain('type Address struct');
    expect(out).toContain('type DataItem struct');
  });

  it('emits definitions when there is no root type', () => {
    expect(
      go({ definitions: { Pet: { type: 'object', required: ['name'], properties: { name: { type: 'string' } } }, ID: { type: 'string' } } }),
    ).toBe(lines('type Pet struct {', '\tName string `json:"name"`', '}', '', 'type ID string'));
  });

  it('declares non-object roots', () => {
    expect(go({ title: 'Names', type: 'array', items: { type: 'string' } })).toBe('type Names []string');
  });

  it('resolves $anchor references', () => {
    const out = go({
      type: 'object',
      properties: { a: { $ref: '#addr' } },
      $defs: { Address: { $anchor: 'addr', type: 'object', properties: { city: { type: 'string' } } } },
    });
    expect(out).toContain('A Address `json:"a,omitempty"`');
    expect(out.match(/type Address struct/g)).toHaveLength(1);
  });

  it('keeps remote references as any', () => {
    expect(go({ type: 'object', properties: { a: { $ref: 'https://example.com/a.json' } } })).toContain(
      'A any `json:"a,omitempty"` // unresolved $ref: https://example.com/a.json',
    );
  });
});

describe('schemaToGo naming', () => {
  it('uses the schema title as root type name', () => {
    expect(go({ title: 'user profile', type: 'object', properties: { id: { type: 'integer' } } })).toMatch(/^type UserProfile struct/);
  });

  it('reuses identical anonymous structs', () => {
    const address = { type: 'object', properties: { city: { type: 'string' } } };
    const out = go({
      type: 'object',
      properties: {
        a: { type: 'object', properties: { address } },
        b: { type: 'object', properties: { address } },
      },
    });
    expect(out.match(/type Address struct/g)).toHaveLength(1);
  });

  it('prefixes conflicting anonymous struct names with their parent', () => {
    const out = go({
      type: 'object',
      properties: {
        a: { type: 'object', properties: { address: { type: 'object', properties: { city: { type: 'string' } } } } },
        b: { type: 'object', properties: { address: { type: 'object', properties: { zip: { type: 'string' } } } } },
      },
    });
    expect(out).toContain('type Address struct {\n\tCity string');
    expect(out).toContain('type BAddress struct {\n\tZip string');
  });
});

describe('schemaToGo options', () => {
  const nested = {
    type: 'object',
    required: ['address'],
    properties: {
      name: { type: 'string' },
      address: { type: 'object', required: ['city'], properties: { city: { type: 'string' } } },
    },
  };

  it('inlines anonymous structs', () => {
    expect(go(nested, inline)).toBe(
      lines(
        'type AutoGenerated struct {',
        '\tName string `json:"name,omitempty"`',
        '\tAddress struct {',
        '\t\tCity string `json:"city"`',
        '\t} `json:"address"`',
        '}',
      ),
    );
  });

  it('adds omitempty to every field', () => {
    const out = go(nested, { ...flat, omitempty: true });
    expect(out).toContain('`json:"address,omitempty"`');
    expect(out).toContain('`json:"city,omitempty"`');
  });

  it('uses pointers for optional fields', () => {
    const out = go(
      { type: 'object', required: ['id'], properties: { id: { type: 'string' }, n: { type: 'integer' }, tags: { type: 'array', items: { type: 'string' } } } },
      { ...flat, pointers: true },
    );
    expect(out).toContain('\tID string `json:"id"`');
    expect(out).toContain('\tN *int `json:"n,omitempty"`');
    expect(out).toContain('\tTags []string `json:"tags,omitempty"`');
  });

  it('is deterministic', () => {
    expect(schemaToGo(JSON.stringify(nested), flat)).toEqual(schemaToGo(JSON.stringify(nested), flat));
  });
});
