import { schemaToGo } from './schema-to-go';

const inline = { inline: true, omitempty: false };
const flat = { inline: false, omitempty: false };

const nested = JSON.stringify({
  type: 'object',
  properties: {
    name: { type: 'string' },
    address: { type: 'object', properties: { city: { type: 'string' } } },
  },
});

describe('schemaToGo', () => {
  it('returns nothing for empty input', () => {
    expect(schemaToGo('  ', inline)).toEqual({ go: '' });
  });

  it('reports invalid JSON', () => {
    expect(schemaToGo('{', inline).error).toMatch(/^Invalid JSON/);
  });

  it('rejects non-object schemas', () => {
    expect(schemaToGo('[]', inline).error).toBe('A JSON Schema must be an object');
  });

  it('generates inline nested structs', () => {
    const { go, error } = schemaToGo(nested, inline);
    expect(error).toBeUndefined();
    expect(go).toBe(
      'type AutoGenerated struct {\n' +
        '\tName string `json:"name"`\n' +
        '\tAddress struct {\n' +
        '\t\tCity string `json:"city"`\n' +
        '\t} `json:"address"`\n' +
        '}',
    );
  });

  it('generates separate types when not inline', () => {
    const { go } = schemaToGo(nested, flat);
    expect(go).toContain('Address Address `json:"address"`');
    expect(go).toContain('type Address struct {\n\tCity string `json:"city"`\n}');
  });

  it('adds omitempty to every field', () => {
    const { go } = schemaToGo(nested, { inline: true, omitempty: true });
    expect(go).toContain('`json:"name,omitempty"`');
    expect(go).toContain('`json:"city,omitempty"`');
  });

  it('uses the schema title as root type name', () => {
    const schema = JSON.stringify({ title: 'user profile', type: 'object', properties: { id: { type: 'integer' } } });
    expect(schemaToGo(schema, inline).go).toMatch(/^type UserProfile struct/);
  });

  it('includes optional properties', () => {
    const schema = JSON.stringify({ type: 'object', required: ['a'], properties: { a: { type: 'string' }, b: { type: 'boolean' } } });
    expect(schemaToGo(schema, inline).go).toContain('B bool `json:"b"`');
  });

  it('types array items from a generated element', () => {
    const schema = JSON.stringify({ type: 'object', properties: { tags: { type: 'array', items: { type: 'string' } } } });
    expect(schemaToGo(schema, inline).go).toContain('Tags []string `json:"tags"`');
  });

  it('maps date-time format to time.Time', () => {
    const schema = JSON.stringify({ type: 'object', properties: { at: { type: 'string', format: 'date-time' } } });
    expect(schemaToGo(schema, inline).go).toContain('At time.Time `json:"at"`');
  });

  it('is deterministic', () => {
    expect(schemaToGo(nested, flat)).toEqual(schemaToGo(nested, flat));
  });
});
